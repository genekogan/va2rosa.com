// Reads what is actually in public/images/<set>/ and writes src/data/galleries.js.
// Run it after adding pictures: `node scripts/build-galleries.mjs`.
// Captions live in CAPTIONS below, keyed by file name, so re-running never
// loses them.
import fs from 'node:fs';
import path from 'node:path';

const SETS = ['pw', 'pw21', 'pwig', 'street', 'sk', 'vc', 'op', 'fest', 'tendler'];
const ROOT = path.join(process.cwd(), 'public', 'images');

const CAPTIONS = JSON.parse(
  fs.existsSync('src/data/captions.json') ? fs.readFileSync('src/data/captions.json', 'utf8') : '{}'
);

const out = {};
for (const s of SETS) {
  const dir = path.join(ROOT, s);
  if (!fs.existsSync(dir)) {
    out[s] = [];
    continue;
  }
  out[s] = fs
    .readdirSync(dir)
    .filter((f) => f.endsWith('.webp'))
    .sort()
    .map((f) => ({ src: `/images/${s}/${f}`, caption: CAPTIONS[f] ?? '' }));
}

const body = `// GENERATED by scripts/build-galleries.mjs. Do not edit by hand:
// add pictures to public/images/<set>/ and re-run the script.
// Captions live in src/data/captions.json, keyed by file name.

export const g = ${JSON.stringify(out, null, 1)};

export const take = (set, from, count) => (g[set] ?? []).slice(from, from + count);
export const slice = (set, from) => (g[set] ?? []).slice(from);
`;
fs.writeFileSync('src/data/galleries.js', body);
console.log(
  Object.entries(out)
    .map(([k, v]) => `${k}: ${v.length}`)
    .join(', ')
);
